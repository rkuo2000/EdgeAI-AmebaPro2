#!/usr/bin/env python3
"""Losslessly pack RGB565 portraits with repeat/literal packets for board flash."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent
NAMES = ('edge_gallery', 'neutral_smile', 'happy_smile', 'waving_wink', 'cheering', 'shy_smile', 'waving')
SOURCES = {'edge_gallery': 'Google_AI_Edge_Gallery'}  # face name -> .hpp stem when they differ


def encode(pixels):
    result = bytearray()
    i = 0
    while i < len(pixels):
        run = 1
        while i + run < len(pixels) and run < 128 and pixels[i + run] == pixels[i]:
            run += 1
        if run >= 3:
            result.append(0x80 | (run - 1))
            result.extend(pixels[i].to_bytes(2, 'big'))
            i += run
        else:
            literal = []
            while i < len(pixels) and len(literal) < 128:
                if i + 2 < len(pixels) and pixels[i] == pixels[i + 1] == pixels[i + 2]:
                    break
                literal.append(pixels[i])
                i += 1
            result.append(len(literal) - 1)
            for pixel in literal:
                result.extend(pixel.to_bytes(2, 'big'))
    return result


def decode(data):
    pixels = []
    i = 0
    while i < len(data):
        control = data[i]
        i += 1
        count = (control & 0x7f) + 1
        if control & 0x80:
            pixel = int.from_bytes(data[i:i + 2], 'big')
            i += 2
            pixels.extend([pixel] * count)
        else:
            for _ in range(count):
                pixels.append(int.from_bytes(data[i:i + 2], 'big'))
                i += 2
    return pixels


def main():
    lines = ['// Generated by pack_faces.py; exact RGB565 pixels, no image resampling.',
             '#pragma once', '#include <stdint.h>', '#include <stddef.h>',
             'struct PetFace { const uint8_t *data; size_t size; };']
    total = 0
    for name in NAMES:
        source = (ROOT / f'{SOURCES.get(name, name)}_240x320_RGB565.hpp').read_text()
        pixels = [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]+', source.split('{', 1)[1].split('}', 1)[0])]
        assert len(pixels) == 240 * 320
        data = encode(pixels)
        assert decode(data) == pixels, name
        total += len(data)
        lines.append(f'static const uint8_t {name}_bytes[] = {{')
        for offset in range(0, len(data), 24):
            lines.append('    ' + ','.join(f'0x{n:02x}' for n in data[offset:offset + 24]) + ',')
        lines.extend(['};', f'static const PetFace {name}_face = {{{name}_bytes, sizeof({name}_bytes)}};'])
    (ROOT / 'PlushPetFaces.h').write_text('\n'.join(lines) + '\n')
    print(f'All seven portraits round-trip exactly; {total} packed bytes, saved {7 * 240 * 320 * 2 - total} bytes')


if __name__ == '__main__':
    main()
